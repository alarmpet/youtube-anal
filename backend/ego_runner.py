class EgoRunner:
    def __init__(self, cdp_port: int = 9222):
        self.cdp_port = cdp_port
        self.is_running = False
        self.current_process: Optional[subprocess.Popen] = None
        self.event_callbacks: List[Callable[[dict], None]] = []
        self.status = {
            "is_running": False,
            "keyword": "",
            "stage": "idle",
            "progress": 0,
            "message": "대기 중입니다.",
            "current_video": 0,
            "total_videos": 0,
            "latest_screen": None,
            "error": None
        }

    def register_callback(self, cb: Callable[[dict], None]):
        if cb not in self.event_callbacks:
            self.event_callbacks.append(cb)

    def unregister_callback(self, cb: Callable[[dict], None]):
        if cb in self.event_callbacks:
            self.event_callbacks.remove(cb)

    def _emit(self, event_type: str, data: dict):
        payload = {
            "type": event_type,
            "timestamp": datetime.now().isoformat(),
            **data
        }
        for cb in list(self.event_callbacks):
            try:
                cb(payload)
            except Exception as e:
                logger.error(f"Error in event callback: {e}")

    def _log(self, message: str, level: str = "info", step: Optional[str] = None):
        self.status["message"] = message
        logger.info(f"[{level.upper()}] {message}")
        self._emit("log", {
            "level": level,
            "message": message,
            "step": step or self.status["stage"]
        })

    def _update_screen(self, image_rel_path: str):
        self.status["latest_screen"] = image_rel_path
        self._emit("screen", {
            "screen_url": f"/workspace/{image_rel_path.replace(os.sep, '/')}",
            "step": self.status["stage"]
        })

    def abort(self):
        self.is_running = False
        if self.current_process and self.current_process.poll() is None:
            try:
                self.current_process.terminate()
                time.sleep(0.5)
                if self.current_process.poll() is None:
                    self.current_process.kill()
            except Exception as e:
                logger.error(f"Error aborting process: {e}")
        self.status["is_running"] = False
        self.status["stage"] = "aborted"
        self._log("작업이 사용자에 의해 중단되었습니다.", level="warning")

