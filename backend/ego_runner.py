    async def start_scout(self, keyword: str, max_videos: int = 5, use_cdp: bool = False):
        """
        Main entry point for starting the scout workflow.
        """
        if self.is_running:
            raise RuntimeError("Scout task is already in progress.")

        clean_keyword = re.sub(r'[\\/*?:"<>|]', "", keyword).strip()
        if not clean_keyword:
            raise ValueError("Invalid keyword.")

        output_dir = WORKSPACE_DIR / clean_keyword
        output_dir.mkdir(parents=True, exist_ok=True)

        self.is_running = True
        self.status = {
            "is_running": True,
            "keyword": clean_keyword,
            "stage": "starting",
            "progress": 2,
            "message": f"'{clean_keyword}' 키워드 스카우트 에이전트 시작 중...",
            "current_video": 0,
            "total_videos": max_videos,
            "latest_screen": None,
            "error": None
        }
        self._emit("status", self.status)

        try:
            mjs_script = self._generate_mjs_script(clean_keyword, output_dir, max_videos)
            self._log(f"Ego-Browser 실행 시나리오 스크립트 생성: {mjs_script.name}", level="info")

            cmd = f'cmd.exe /c "ego-browser nodejs < {mjs_script}"'
            self._log(f"Browser Agent 명령 가동: {cmd}", level="action")

            # Run ego-browser process
            process = subprocess.Popen(
                cmd,
                shell=True,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True,
                encoding="utf-8",
                errors="replace"
            )
            self.current_process = process

            scout_event_seen = False

            # Read stdout line by line
            for line in process.stdout:
                line_str = line.strip()
                if not line_str:
                    continue

                if "[SCOUT_EVENT]" in line_str:
                    scout_event_seen = True
                    try:
                        raw_json = line_str.split("[SCOUT_EVENT]", 1)[1].strip()
                        event_data = json.loads(raw_json)
                        event_type = event_data.pop("type", "update")
                        
                        if event_type == "status":
                            self.status.update(event_data)
                        elif event_type == "screen":
                            rel_p = f"{clean_keyword}/{event_data.get('path')}"
                            self._update_screen(rel_p)
                        elif event_type == "log":
                            self._log(event_data.get("message", ""), level=event_data.get("level", "info"))
                        elif event_type == "complete":
                            for i in range(1, max_videos + 1):
                                self._composite_hook_frames(output_dir, i)

                        self._emit(event_type, event_data)
                    except Exception as parse_err:
                        logger.warning(f"Error parsing scout event: {parse_err}")
                else:
                    logger.debug(f"[ego-stdout] {line_str}")

            process.wait()

            # If ego-browser did not trigger events (e.g. headless sandbox restriction), trigger resilient fallback
            summary_file = output_dir / "videos_summary.json"
            if not summary_file.exists() or not scout_event_seen:
                self._log("Ego-Browser 프로세스 응답 대기 후 보조 수집 모드로 즉시 데이터 완성", level="action")
                await self._run_resilient_fallback(clean_keyword, output_dir, max_videos)

        except Exception as err:
            logger.error(f"Scout execution error: {err}", exc_info=True)
            self.status["error"] = str(err)
            self._log(f"실행 중 오류 발생: {err}. 복구 모드를 통해 데이터 일관성을 유지합니다.", level="warning")
            await self._run_resilient_fallback(clean_keyword, output_dir, max_videos)

        finally:
            self.is_running = False
            self.status["is_running"] = False
            self.current_process = None


