    def _composite_hook_frames(self, output_dir: Path, video_index: int):
        """
        Combines 0s, 5s, and 15s keyframes into a single side-by-side video_{n}_hook_frames.png
        """
        f0 = output_dir / f"video_{video_index}_hook_0.png"
        f5 = output_dir / f"video_{video_index}_hook_5.png"
        f15 = output_dir / f"video_{video_index}_hook_15.png"
        out_file = output_dir / f"video_{video_index}_hook_frames.png"

        valid_images = []
        for p in [f0, f5, f15]:
            if p.exists():
                try:
                    img = Image.open(p)
                    valid_images.append(img)
                except Exception:
                    pass

        if not valid_images:
            return

        w, h = valid_images[0].size
        composite = Image.new("RGB", (w * len(valid_images), h), color=(15, 23, 42))
        for idx, img in enumerate(valid_images):
            composite.paste(img.resize((w, h)), (idx * w, 0))

        composite.save(out_file, quality=90)

